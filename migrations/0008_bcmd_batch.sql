-- 0008: bcmd_batch, local BCMD candidate based on reviewed spec Revision 4.
-- Proposed for release; do not apply remotely without exact-schema/target verification.
CREATE TABLE IF NOT EXISTS `bcmd_batch` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `public_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `name` varchar(120) NOT NULL,
  `category` char(2) NOT NULL,
  `source_agency` char(4) NOT NULL DEFAULT 'CHED',
  `criteria` json NOT NULL,
  `status` varchar(16) NOT NULL DEFAULT 'DQA_COMPLETED',
  `policy_version` varchar(32) NOT NULL,
  `entitlement_def_version` varchar(16) NOT NULL,
  `dqa_ruleset_id` varchar(32) NOT NULL,
  `dqa_ruleset_version` varchar(32) NOT NULL,
  `dqa_ruleset_sha256` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `dqa_config_sha256` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `dqa_config_canonical` text CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `dqa_evaluation_date` date NOT NULL,
  `snapshot_started_at` datetime(3) NOT NULL,
  `source_input_sha256` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `dqa_completed_at` datetime(3) NOT NULL,
  `candidate_count` int unsigned NOT NULL,
  `member_count` int unsigned NOT NULL,
  `excluded_not_eligible` int unsigned NOT NULL,
  `excluded_no_tuloy_id` int unsigned NOT NULL,
  `excluded_duplicate_episode` int unsigned NOT NULL,
  `dqa_pass_count` int unsigned NOT NULL,
  `dqa_warn_count` int unsigned NOT NULL,
  `dqa_block_count` int unsigned NOT NULL,
  `dqa_warn_issue_count` int unsigned NOT NULL,
  `dqa_block_issue_count` int unsigned NOT NULL,
  `dqa_outcome` varchar(8) NOT NULL,
  `export_seq` int unsigned NOT NULL DEFAULT 0,
  `created_by_api_user_id` int NOT NULL,
  `created_by_agency` varchar(16) NOT NULL,
  `request_id` varchar(64) NOT NULL,
  `idempotency_key` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `request_hash` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `created_at` timestamp(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `purged_at` timestamp(3) NULL DEFAULT NULL,
  `purged_by` varchar(255) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_bcmd_batch_public` (`public_id`),
  UNIQUE KEY `uq_bcmd_batch_idem` (`created_by_api_user_id`, `idempotency_key`),
  KEY `ix_bcmd_batch_list` (`created_at`, `id`),
  CONSTRAINT `fk_bcmd_batch_creator` FOREIGN KEY (`created_by_api_user_id`) REFERENCES `api_users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `ck_bcmd_batch_category` CHECK (`category` IN ('TK','TA','TT')),
  CONSTRAINT `ck_bcmd_batch_source` CHECK (`source_agency` = 'CHED'),
  CONSTRAINT `ck_bcmd_batch_status` CHECK (`status` IN ('DQA_COMPLETED','EXPORTED','PURGED')),
  CONSTRAINT `ck_bcmd_batch_outcome` CHECK (`dqa_outcome` IN ('CLEAN','WARN','BLOCKED')),
  CONSTRAINT `ck_bcmd_batch_members` CHECK (`dqa_pass_count` + `dqa_warn_count` + `dqa_block_count` = `member_count`),
  CONSTRAINT `ck_bcmd_batch_accounting` CHECK (`candidate_count` = `member_count` + `excluded_not_eligible` + `excluded_no_tuloy_id` + `excluded_duplicate_episode`),
  CONSTRAINT `ck_bcmd_batch_outcome_rule` CHECK (`dqa_outcome` = CASE WHEN `dqa_block_issue_count` > 0 THEN 'BLOCKED' WHEN `dqa_warn_issue_count` > 0 THEN 'WARN' ELSE 'CLEAN' END),
  CONSTRAINT `ck_bcmd_batch_clean` CHECK (`dqa_outcome` <> 'CLEAN' OR (`dqa_pass_count` = `member_count` AND `member_count` > 0)),
  CONSTRAINT `ck_bcmd_batch_purge` CHECK ((`status` = 'PURGED') = (`purged_at` IS NOT NULL)),
  CONSTRAINT `ck_bcmd_batch_config_hash` CHECK (`dqa_config_sha256` = SHA2(`dqa_config_canonical`, 256))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
